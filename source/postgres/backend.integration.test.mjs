import {test} from 'node:test';
import assert from 'node:assert/strict';
import {db as connection, run} from '../src/database.js';
const core = await import('../src/db.js');
test('real PostgreSQL: settings, account, session, category, catalog', async () => {
  assert.equal(await core.getSetting('currency'), 'EUR');
  await core.setSettings([['integration_marker','ok'],['integration_marker2','ok']]);
  assert.equal(await core.getSetting('integration_marker'),'ok');
  const userId=await core.createUser('integration@example.invalid','fixture-not-a-real-password-hash','customer','Integration User');
  assert.ok(Number.isSafeInteger(userId)&&userId>0);
  const sessionId=await core.createSession(userId);
  const session=await core.getSession(sessionId);
  assert.equal(session.user_id,userId);
  const categoryId=await core.createCategory('Integration category','integration-category');
  assert.ok(categoryId>0);
  assert.ok((await core.listCategories()).some(c=>c.id===categoryId));
  const product=await run('INSERT INTO products(name,slug,sku,price_cents,stock,category_id,active) VALUES(?,?,?,?,?,?,?)',['Integration product','integration-product','INTEGRATION-001',1599,8,categoryId,1]);
  assert.ok(product.lastInsertRowid>0);
  assert.equal((await core.getProductById(product.lastInsertRowid)).name,'Integration product');
  assert.equal(await core.countProducts({search:'integration'}),1);
  assert.ok((await core.listProducts({search:'integration',category:'integration-category'})).some(p=>p.id===product.lastInsertRowid));
});
test('real PostgreSQL: manager MFA enrollment, exact credential proof, challenge, attempt limit and replay protection',async()=>{
  const proof={email:'mfa-fixture@example.invalid',passwordHash:'not-a-real-password-hash',role:'manager'};
  const id=await core.createUser(proof.email,proof.passwordHash,proof.role,'CI Manager');
  const seed='fixture-encrypted-secret';
  assert.equal(await core.setManagerMfaSecret(id,seed,{...proof,email:proof.email.toUpperCase()}),false);
  assert.equal(await core.setManagerMfaSecret(id,seed,proof),true);
  const sid=await core.createSession(null,300000);
  await core.setSessionCsrf(sid,'fixture-csrf');
  await core.saveSessionCart(sid,[]);
  await core.saveSessionWishlist(sid,[]);
  await core.saveSessionCoupon(sid,null);
  const expiry=Date.now()+300000;
  assert.equal(await core.setSessionExpiresAt(sid,expiry),true);
  await assert.rejects(()=>core.createMfaLoginChallenge(sid,{userId:id,mode:'setup',expiresAtMs:Date.now()-1000,credentialProof:proof}));
  await core.createMfaLoginChallenge(sid,{userId:id,mode:'setup',expiresAtMs:expiry,credentialProof:proof});
  assert.equal((await core.getMfaLoginChallenge(sid)).mode,'setup');
  for(let i=1;i<=6;i++)assert.equal((await core.consumeMfaAttempt(id,'fixture',Date.now(),900000,5)).allowed,i<=5);
  assert.equal(await core.activateManagerMfa(id,{lastTotpStep:100,recoveryHashes:'[]',expectedSecret:seed,credentialProof:proof}),true);
  assert.equal(await core.getMfaLoginChallenge(sid),undefined);
  assert.equal(await core.updateManagerTotpStep(id,100),false);
  assert.equal(await core.updateManagerTotpStep(id,101),true);
  const authenticated=await core.createAuthenticatedSession(id,proof);
  assert.equal((await core.getSession(authenticated)).user_id,id);
});
test('real PostgreSQL: category search, wishlist persistence and inactive product rejection',async()=>{
  const categoryId=await core.createCategory('Wishlist fixtures','wishlist-fixtures');
  const product=await run('INSERT INTO products(name,slug,sku,price_cents,stock,category_id,active) VALUES(?,?,?,?,?,?,?)',['Wishlist fixture item','wishlist-fixture-item','WISH-CI-001',1200,3,categoryId,1]);
  const id=product.lastInsertRowid;
  assert.ok(id>0);
  assert.equal(await core.countProducts({search:'Wishlist fixture item',category:'wishlist-fixtures'}),1);
  assert.ok((await core.listProducts({search:'Wishlist fixture item',category:'wishlist-fixtures'})).some(p=>p.id===id));
  const sid=await core.createSession(null,300000);
  assert.deepEqual((await core.toggleWishlist(sid,id)).wishlist,[id]);
  const stored=await core.getSession(sid);
  assert.deepEqual(JSON.parse(stored.wishlist_json),[id]);
  assert.deepEqual((await core.toggleWishlist(sid,id)).wishlist,[]);
  await run('UPDATE products SET active=0 WHERE id=?',[id]);
  assert.equal((await core.toggleWishlist(sid,id)).reason,'product-unavailable');
  assert.equal(await core.countProducts({search:'Wishlist fixture item',category:'wishlist-fixtures'}),0);
});
test('real PostgreSQL: product edit cannot bypass reserved-stock visibility guard',async()=>{
  const data={name:'Visibility guard fixture',slug:'visibility-guard-fixture',sku:'VIS-GUARD-CI-001',shortDescription:'CI fixture',description:'CI fixture',imageUrl:'',galleryImages:[],priceCents:1200,costPriceCents:500,salePriceCents:null,saleStart:null,saleEnd:null,automaticDiscountPercent:0,stock:5,reorderLevel:0,categoryId:null,tags:'ci',featured:false,active:true,variants:[],variantOptionName:'Size',variantOptionName2:''};
  const id=await core.adminCreateOrUpdateProduct(data);
  await run('UPDATE products SET reserved_stock=2 WHERE id=?',[id]);
  assert.equal(await core.archiveProduct(id),false);
  await assert.rejects(()=>core.adminCreateOrUpdateProduct({...data,id,active:false}),{message:'RESERVED_PRODUCT_VISIBILITY'});
  assert.equal(Number((await core.getProductById(id)).active),1);
  await core.adminCreateOrUpdateProduct({...data,id,name:'Visibility guard updated'});
  assert.equal((await core.getProductById(id)).name,'Visibility guard updated');
  await run('UPDATE products SET reserved_stock=0 WHERE id=?',[id]);
  await core.adminCreateOrUpdateProduct({...data,id,active:false});
  assert.equal(Number((await core.getProductById(id)).active),0);
});
