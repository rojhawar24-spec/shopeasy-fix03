-- PostgreSQL staging schema candidate derived from FIX03 database-schema.json.

-- Runtime adapter, seeds, SQL queries and cross-instance controls require separate porting.

CREATE SCHEMA shopeasy;

CREATE EXTENSION IF NOT EXISTS citext WITH SCHEMA extensions;

REVOKE ALL ON SCHEMA shopeasy FROM PUBLIC, anon, authenticated, service_role;

CREATE TABLE shopeasy.account_login_limits (
  email_hash TEXT PRIMARY KEY,
  window_started_at_ms BIGINT NOT NULL,
  attempts BIGINT NOT NULL DEFAULT 0 CHECK(attempts >= 0),
  blocked_until_ms BIGINT NOT NULL DEFAULT 0
);

ALTER TABLE shopeasy.account_login_limits ENABLE ROW LEVEL SECURITY;

CREATE TABLE shopeasy.asset_storage_quota (
  id BIGINT PRIMARY KEY CHECK(id=1),
  used_bytes BIGINT NOT NULL DEFAULT 0 CHECK(used_bytes >= 0),
