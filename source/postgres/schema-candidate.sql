CREATE FUNCTION shopeasy.order_status_insert() RETURNS trigger LANGUAGE plpgsql SECURITY INVOKER SET search_path = pg_catalog, shopeasy AS $$
BEGIN
 INSERT INTO shopeasy.order_status_history(order_id,from_status,to_status,actor_type,actor_user_id,note,created_at)
 VALUES(NEW.id,NULL,NEW.status,COALESCE(NEW.last_status_actor_type,'system'),NEW.last_status_actor_user_id,'Order placed',COALESCE(NEW.created_at,to_char(statement_timestamp() AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS')));
 RETURN NEW;
END; $$;
CREATE TRIGGER orders_status_history_after_insert AFTER INSERT ON shopeasy.orders FOR EACH ROW EXECUTE FUNCTION shopeasy.order_status_insert();
CREATE FUNCTION shopeasy.order_status_update() RETURNS trigger LANGUAGE plpgsql SECURITY INVOKER SET search_path = pg_catalog, shopeasy AS $$
BEGIN
 INSERT INTO shopeasy.order_status_history(order_id,from_status,to_status,actor_type,actor_user_id,note,created_at)
 VALUES(NEW.id,OLD.status,NEW.status,COALESCE(NEW.last_status_actor_type,'system'),NEW.last_status_actor_user_id,CASE WHEN NEW.status='cancelled' THEN COALESCE(NULLIF(NEW.cancellation_reason,''),'Order cancelled') ELSE '' END,COALESCE(NEW.updated_at,to_char(statement_timestamp() AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS')));
 RETURN NEW;
END; $$;
CREATE TRIGGER orders_status_history_after_update AFTER UPDATE OF status ON shopeasy.orders FOR EACH ROW WHEN (NEW.status IS DISTINCT FROM OLD.status) EXECUTE FUNCTION shopeasy.order_status_update();
CREATE FUNCTION shopeasy.gallery_limit() RETURNS trigger LANGUAGE plpgsql SECURITY INVOKER SET search_path = pg_catalog, shopeasy AS $$
BEGIN
 IF TG_OP = 'UPDATE' THEN IF NEW.product_id = OLD.product_id THEN RETURN NEW; END IF; END IF;
 PERFORM 1 FROM shopeasy.products WHERE id=NEW.product_id FOR UPDATE;
 IF (SELECT count(*) FROM shopeasy.product_images WHERE product_id=NEW.product_id)>=6 THEN RAISE EXCEPTION 'IMAGE_GALLERY_LIMIT' USING ERRCODE='23514'; END IF;
 RETURN NEW;
END; $$;
CREATE TRIGGER trg_product_images_max_six_insert BEFORE INSERT ON shopeasy.product_images FOR EACH ROW EXECUTE FUNCTION shopeasy.gallery_limit();
CREATE TRIGGER trg_product_images_max_six_move BEFORE UPDATE OF product_id ON shopeasy.product_images FOR EACH ROW EXECUTE FUNCTION shopeasy.gallery_limit();
CREATE FUNCTION shopeasy.asset_quota_delete() RETURNS trigger LANGUAGE plpgsql SECURITY INVOKER SET search_path = pg_catalog, shopeasy AS $$
BEGIN
 UPDATE shopeasy.asset_storage_quota SET used_bytes=GREATEST(0,used_bytes-COALESCE(octet_length(OLD.data),0)) WHERE id=1;
 RETURN OLD;
END; $$;
CREATE TRIGGER uploaded_assets_quota_after_delete AFTER DELETE ON shopeasy.uploaded_assets FOR EACH ROW EXECUTE FUNCTION shopeasy.asset_quota_delete();
