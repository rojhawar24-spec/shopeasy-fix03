#!/usr/bin/env node
// Reproducible CSS delivery build. No selectors/declarations are purged, merged,
// reordered or converted. Readable authoring sources remain in public/css.
import fs from 'node:fs';
import path from 'node:path';
import { createHash } from 'node:crypto';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';
import CleanCSS from 'clean-css';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const require = createRequire(import.meta.url);
const minifierVersion = require('clean-css/package.json').version;
if (minifierVersion !== '5.3.3') throw new Error('The CSS build requires the exact locked clean-css5.3.3.');
const checkOnly = process.argv.slice(2).includes('--check');
if (process.argv.slice(2).some(value => value !== '--check')) throw new Error('Usage: node scripts/build-design-css.mjs [--check]');
const hash = bytes => createHash('sha256').update(bytes).digest('hex');
const groups = [
  { output: 'design-foundation.min.css', sources: ['app.css', 'design-tokens.css', 'retail-2027.css', 'editorial-2027.css'] },
  { output: 'design-polish.min.css', sources: ['research-polish-2027.css'] }
];
const cssDirectory = path.join(root, 'public/css');
const manifest = { schema: 1, minifier: { name: 'clean-css', version: minifierVersion, level: 0, rebase: false, inline: 'none', selectorPurging: false }, bundles: [] };
const writes = [];
for (const group of groups) {
  const inputs = group.sources.map(name => {
    const filename = path.join(cssDirectory, name);
    const stat = fs.lstatSync(filename);
    if (!stat.isFile() || stat.isSymbolicLink()) throw new Error(`Expected a regular stylesheet: ${name}`);
    const bytes = fs.readFileSync(filename);
    return { name, filename, bytes, sha256: hash(bytes) };
  });
  const combined = inputs.map(input => input.bytes.toString('utf8')).join('\n');
  // Level0 keeps the original CSS rule/declaration order and values. The parser
  // serializes whitespace/comments; URL rebasing and remote inlining are off.
  const result = new CleanCSS({ level: 0, rebase: false, inline: ['none'] }).minify(combined);
  if (result.errors.length) throw new Error(`CSS parse failed for ${group.output}: ${result.errors.join('; ')}`);
  const banner = `/*! Generated by build-design-css.mjs from ${group.sources.join(', ')}; see original sources and third-party notices. */\n`;
  const content = Buffer.from(banner + result.styles + '\n');
  for (const input of inputs) if (hash(fs.readFileSync(input.filename)) !== input.sha256) throw new Error('CSS source changed during the build; retry in a stable source copy.');
  const relative = 'public/css/' + group.output;
  writes.push([path.join(root, relative), content]);
  manifest.bundles.push({ output: relative, sha256: hash(content), inputBytes: inputs.reduce((total, input) => total + input.bytes.length, 0), bytes: content.length,
    sources: inputs.map(({ name, bytes, sha256 }) => ({ path: 'public/css/' + name, bytes: bytes.length, sha256 })), warnings: result.warnings });
}
// The static cascade audit compares base URLs; runtime EJS adds validated cache suffixes.
const header = fs.readFileSync(path.join(root, 'views/partials/header.ejs'), 'utf8').replace(/<%[\s\S]*?%>/g,'');
const runtime = [...header.matchAll(/<link\s+rel="stylesheet"\s+href="([^"?]+)\?v=([^"?]+)"/g)];
const expected = ['/css/design-foundation.min.css', '/theme/shop.css', '/css/design-polish.min.css'];
if (JSON.stringify(runtime.map(([, href]) => href)) !== JSON.stringify(expected)) throw new Error('The runtime must preserve foundation → dynamic /theme/shop.css → polish cascade order.');
const duplicates = new Set(runtime.map(([, href]) => href));
if (duplicates.size !== runtime.length) throw new Error('Duplicate runtime stylesheets.');
for (const previewName of fs.readdirSync(root).filter(name => /^PREVIEW.*\.html$/.test(name))) {
  const preview = fs.readFileSync(path.join(root, previewName), 'utf8');
  for (const [, href, version] of runtime.filter(([, href]) => href.startsWith('/css/'))) {
    if (!preview.includes(`./public${href}?v=${version}`)) throw new Error(`Preview CSS layer/version differs: ${previewName} ${href}`);
  }
}
writes.push([path.join(root, 'generated/design-css-manifest.json'), Buffer.from(JSON.stringify(manifest, null, 2) + '\n')]);
for (const [destination, content] of writes) {
  if (checkOnly) {
    if (!fs.existsSync(destination) || !fs.readFileSync(destination).equals(content)) throw new Error(`Generated CSS is stale: ${path.relative(root, destination)}. Run npm run build:design-css.`);
    continue;
  }
  if (fs.existsSync(destination) && fs.readFileSync(destination).equals(content)) continue;
  fs.mkdirSync(path.dirname(destination), { recursive: true });
  const temporary = fs.mkdtempSync(path.join(path.dirname(destination), '.design-css-build-'));
  try { const file = path.join(temporary, 'content'); fs.writeFileSync(file, content, { flag: 'wx' }); fs.renameSync(file, destination); }
  finally { fs.rmSync(temporary, { recursive: true, force: true }); }
}
console.log(`Design CSS ${checkOnly ? 'verification' : 'build'} passed: five versioned static layers compiled to two deterministic assets, with dynamic /theme/shop.css between them; no CSS purging or selector/declaration reordering.`);
