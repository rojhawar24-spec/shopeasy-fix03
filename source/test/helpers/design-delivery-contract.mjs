import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import {createHash} from 'node:crypto';
import {fileURLToPath} from 'node:url';

const root = fileURLToPath(new URL('../../', import.meta.url));
const digest = value => createHash('sha256').update(value).digest('hex');
const groups = [
  ['public/css/app.css', 'public/css/design-tokens.css', 'public/css/retail-2027.css', 'public/css/editorial-2027.css'],
  ['public/css/research-polish-2027.css']
];
const outputs = ['public/css/design-foundation.min.css', 'public/css/design-polish.min.css'];

function stylesheets(source) {
  return [...source.matchAll(/<link\b[^>]*>/gi)].flatMap(([tag]) => {
    if (!/\brel=["']stylesheet["']/i.test(tag)) return [];
    const href = tag.match(/\bhref=["']([^"']+)["']/i)?.[1];
    assert.ok(href, 'stylesheet links require an href');
    return [href];
  });
}

/** Verify current generated bytes and authored sources, not historical CSS links. */
export function assertDesignDelivery(previews = ['PREVIEW.html', 'PREVIEW-MANAGER.html']) {
  const manifest = JSON.parse(fs.readFileSync(path.join(root, 'generated/design-css-manifest.json'), 'utf8'));
  assert.equal(manifest.schema, 1);
  assert.equal(manifest.minifier.name, 'clean-css');
  assert.equal(manifest.minifier.level, 0, 'delivery build must not reorder/purge authoring rules');
  assert.equal(manifest.minifier.selectorPurging, false);
  assert.deepEqual(manifest.bundles.map(bundle => bundle.output), outputs);
  for (const [index, bundle] of manifest.bundles.entries()) {
    assert.deepEqual(bundle.sources.map(source => source.path), groups[index], 'retain every authoring layer in its original cascade order');
    let inputBytes = 0;
    for (const source of bundle.sources) {
      const bytes = fs.readFileSync(path.join(root, source.path));
      assert.equal(bytes.length, source.bytes, `stale source size: ${source.path}`);
      assert.equal(digest(bytes), source.sha256, `stale source digest: ${source.path}`);
      inputBytes += bytes.length;
    }
    assert.equal(bundle.inputBytes, inputBytes);
    const bytes = fs.readFileSync(path.join(root, bundle.output));
    assert.equal(bytes.length, bundle.bytes, `stale generated size: ${bundle.output}`);
    assert.equal(digest(bytes), bundle.sha256, `stale generated digest: ${bundle.output}`);
    assert.deepEqual(bundle.warnings, []);
  }
  const links = stylesheets(fs.readFileSync(path.join(root, 'views/partials/header.ejs'), 'utf8'));
  const urls = links.map(href => new URL(href, 'https://asset-audit.invalid'));
  assert.deepEqual(urls.map(url => url.pathname), ['/css/design-foundation.min.css', '/theme/shop.css', '/css/design-polish.min.css'], 'keep compiled foundation → configured dynamic theme → compiled polish; no duplicate raw stylesheet requests');
  assert.ok(links.every(href => href.startsWith('/')), 'runtime stylesheet URLs must be same-origin local paths');
  const versions = new Map();
  for (const url of urls) {
    assert.deepEqual([...url.searchParams.keys()], ['v']);
    const version = url.searchParams.get('v');
    assert.match(version, /^[A-Za-z0-9._-]+$/, 'every active stylesheet must have a cache key');
    versions.set(url.pathname, version);
  }
  for (const preview of previews) {
    const css = stylesheets(fs.readFileSync(path.join(root, preview), 'utf8'));
    assert.deepEqual(css.map(href => href.split('?')[0]), outputs.map(output => './' + output), `${preview}: exactly two relative compiled stylesheet files`);
    for (const href of css) {
      const url = new URL(href, 'https://asset-audit.invalid');
      const runtimePath = url.pathname.replace(/^\/public\//, '/');
      assert.equal(url.searchParams.get('v'), versions.get(runtimePath), `${preview}: cache key must match the corresponding runtime bundle`);
    }
  }
  return {manifest, links, versions};
}
